# Codex Quota Keeper - one-shot anchor alarm adapter for Windows Task Scheduler.
# The pure plan function is the test surface; the adapter only wakes runner.ps1.

$script:CqkAnchorAlarmDir = Split-Path -Parent $PSCommandPath
if (-not (Get-Command Get-KeeperRoot -ErrorAction SilentlyContinue)) {
    . (Join-Path $script:CqkAnchorAlarmDir 'common.ps1')
}
if (-not (Get-Command Get-BucketWindowMap -ErrorAction SilentlyContinue)) {
    . (Join-Path $script:CqkAnchorAlarmDir 'state-machine.ps1')
}

function Get-AnchorAlarmTaskName {
    param([hashtable]$Config)
    if ($Config.task -is [hashtable] -and -not [string]::IsNullOrWhiteSpace([string]$Config.task.alarmName)) {
        return [string]$Config.task.alarmName
    }
    return ([string]$Config.task.name + '.AnchorAlarm')
}

function Get-AnchorAlarmPlan {
    param([hashtable]$Config, [hashtable]$State, [DateTime]$Now = (Get-Date), [switch]$RecoverPendingSchedule)
    $name = Get-AnchorAlarmTaskName $Config
    $aa = Get-AutoAnchorConfig $Config
    if (-not (Test-AutoAnchorArmed $Config)) {
        return @{ action = 'clear'; taskName = $name; targetEpoch = $null; targetAt = $null; reason = 'expiry anchoring is not armed' }
    }
    $nowEpoch = ConvertTo-EpochSeconds $Now
    $targets = @()
    foreach ($win in @((Get-BucketWindowMap @($State.buckets)).Values)) {
        if ([string]$win.windowType -notin @($aa.anchorOnExpiry)) { continue }
        # Only a real boundary is worth waking for. An idle window predicts
        # now + duration on every poll, so arming that would push the alarm
        # forward forever and it would never fire.
        $key = Get-WindowKey ([string]$win.bucketId) ([string]$win.windowType)
        $observation = if ($State.windowObservations) { $State.windowObservations[$key] } else { $null }
        if (Test-WindowRunning -Window $win -NowEpoch $nowEpoch -Observation $observation) { $targets += ([long]$win.resetsAt + 60) }
    }
    # The idle guard needs observations at least 30 seconds apart. A minute
    # leaves room for task registration and preserves the confirmation on read.
    $recoveryAt = $Now.AddMinutes(1)
    $recoveryEpoch = ConvertTo-EpochSeconds $recoveryAt
    if ($RecoverPendingSchedule -and @($aa.schedule).Count -gt 0) {
        # Reuse the normal guards on copies: planning must neither consume a
        # slot nor revive an expired one. Only pending daily schedules qualify;
        # the normal runner will read again and enforce leadership/Claim guards.
        $scheduleConfig = ConvertTo-HashtableDeep $Config
        $scheduleConfig.codex.autoAnchor.anchorOnExpiry = @()
        $scheduleState = ConvertTo-HashtableDeep $State
        $decision = Test-ShouldAnchor -Config $scheduleConfig -State $scheduleState -Events @() -IsLeader $true -Now $Now
        if ($decision.should) {
            $atTarget = Test-ShouldAnchor -Config $scheduleConfig -State $scheduleState -Events @() -IsLeader $true -Now $recoveryAt
            $stillDue = @($decision.eventIds | Where-Object { $_ -in @($atTarget.eventIds) })
            if ($stillDue.Count -gt 0) { $targets += $recoveryEpoch }
        }
    }
    if ($targets.Count -eq 0) {
        return @{ action = 'clear'; taskName = $name; targetEpoch = $null; targetAt = $null; reason = 'no future tracked expiry' }
    }
    $targetEpoch = [long](($targets | Measure-Object -Minimum).Minimum)
    $scheduleRecovery = ($RecoverPendingSchedule -and $targetEpoch -eq $recoveryEpoch)
    return @{
        action = 'set'; taskName = $name; targetEpoch = $targetEpoch
        targetAt = ConvertFrom-EpochSeconds $targetEpoch
        reason = $(if ($scheduleRecovery) { 'pending schedule after quota read recovery' } else { 'earliest tracked expiry plus one minute' })
        scheduleRecovery = [bool]$scheduleRecovery
    }
}

function Get-AnchorAlarmLauncherSpec {
    param([string]$KeeperRoot, [string]$ConfigFile, [switch]$ReadOnlyRetry, [switch]$ScheduleRecovery, [switch]$NoWrite)
    $root = Get-KeeperRoot $KeeperRoot
    if (-not $ConfigFile) { $ConfigFile = Get-ConfigPath $root }
    $pwsh = Get-KeeperPowerShellPath
    $wscript = Get-Command wscript -ErrorAction SilentlyContinue
    if (-not $pwsh -or -not $wscript) { throw 'PowerShell and wscript.exe are required for the expiry alarm task' }
    $runner = Join-Path $root 'scripts\runner.ps1'
    $inner = ('"{0}" -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{1}" -KeeperRoot "{2}" -ConfigFile "{3}" -FromAlarm -WaitLockSeconds 60' -f `
        $pwsh, $runner, $root, [System.IO.Path]::GetFullPath($ConfigFile))
    if ($ReadOnlyRetry) { $inner = $inner.Replace('-FromAlarm', '-ReadOnlyRetry') }
    elseif ($ScheduleRecovery) { $inner = $inner.Replace('-FromAlarm', '-ScheduleRecovery') }
    $runtimeDir = Join-Path $root 'runtime'
    $vbsPath = Join-Path $runtimeDir $(if ($ReadOnlyRetry) { 'hidden-launch-read-retry.vbs' } else { 'hidden-launch-anchor-alarm.vbs' })
    $lines = @(
        "' Generated by Codex Quota Keeper - do not edit."
        'On Error Resume Next'
        ('CreateObject("WScript.Shell").Run "{0}", 0, False' -f ($inner -replace '"', '""'))
        'If Err.Number <> 0 Then WScript.Quit 1'
    )
    $content = ($lines -join "`r`n") + "`r`n"
    if (-not $NoWrite) {
        Ensure-Directory $runtimeDir | Out-Null
        [System.IO.File]::WriteAllText($vbsPath, $content, (New-Object System.Text.UTF8Encoding($false)))
    }
    return @{ exe = $wscript.Source; arguments = '//B //NoLogo "{0}"' -f $vbsPath; innerCommand = $inner; vbsPath = $vbsPath; content = $content }
}

function Sync-AnchorAlarmTask {
    param([hashtable]$Config, [hashtable]$State, [string]$KeeperRoot, [string]$ConfigFile, [DateTime]$Now = (Get-Date), [switch]$RecoverPendingSchedule)
    $plan = Get-AnchorAlarmPlan -Config $Config -State $State -Now $Now -RecoverPendingSchedule:$RecoverPendingSchedule
    return Sync-KeeperOneShotTask -Config $Config -Plan $plan -KeeperRoot $KeeperRoot -ConfigFile $ConfigFile
}

function Get-QuotaReadRetryPlan {
    param([hashtable]$Config, [hashtable]$Read, [bool]$IsRetry, [datetime]$Now = (Get-Date))
    $plan = @{ action = 'clear'; taskName = "$($Config.task.name).ReadRetry"; targetAt = $null; targetEpoch = $null; reason = 'no pending read retry' }
    # One extra read per normal tick, never another retry from the retry itself.
    # Short pollers already revisit within the network backoff window.
    $delay = [Math]::Max(10, (Get-PollConfig $Config).minimumIntervalMinutes)
    if (-not $IsRetry -and -not $Read.ok -and $Read.errorKind -in @('NETWORK_ERROR', 'TIMEOUT', 'EOF') -and
        (Get-PollConfig $Config).intervalMinutes -gt $delay) {
        $plan.action = 'set'; $plan.targetAt = $Now.AddMinutes($delay).AddSeconds(5)
        $plan.targetEpoch = ConvertTo-EpochSeconds $plan.targetAt
        $plan.reason = 'one read-only retry after network backoff'
    }
    return $plan
}

function Test-OneShotTaskMatches {
    param($Existing, $Plan, $Launcher, $Action, $Settings, $Principal)
    if (-not $Existing -or @($Existing.Actions).Count -ne 1 -or @($Existing.Triggers).Count -ne 1) { return $false }
    $boundary = [datetime]::MinValue
    if (-not [datetime]::TryParse([string]$Existing.Triggers[0].StartBoundary, [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::AssumeLocal, [ref]$boundary) -or
        (ConvertTo-EpochSeconds $boundary) -ne $Plan.targetEpoch) { return $false }
    if ($Existing.Settings.Enabled -eq $false -or $Existing.Triggers[0].Enabled -eq $false) { return $false }
    foreach ($key in @('Execute', 'Arguments', 'WorkingDirectory')) {
        if ([string]$Existing.Actions[0].$key -ne [string]$Action.$key) { return $false }
    }
    foreach ($key in @('MultipleInstances', 'ExecutionTimeLimit', 'StartWhenAvailable', 'DisallowStartIfOnBatteries', 'StopIfGoingOnBatteries', 'WakeToRun', 'RunOnlyIfNetworkAvailable')) {
        if ([string]$Existing.Settings.$key -ne [string]$Settings.$key) { return $false }
    }
    $actualUser = [string]$Existing.Principal.UserId
    $desiredUser = [string]$Principal.UserId
    if ($actualUser -ne $desiredUser) {
        try {
            if ($actualUser -notmatch '^S-1-') { $actualUser = ([Security.Principal.NTAccount]::new($actualUser)).Translate([Security.Principal.SecurityIdentifier]).Value }
            if ($desiredUser -notmatch '^S-1-') { $desiredUser = ([Security.Principal.NTAccount]::new($desiredUser)).Translate([Security.Principal.SecurityIdentifier]).Value }
        } catch { return $false }
        if ($actualUser -ne $desiredUser) { return $false }
    }
    foreach ($key in @('LogonType', 'RunLevel')) {
        if ([string]$Existing.Principal.$key -ne [string]$Principal.$key) { return $false }
    }
    return ((Test-Path -LiteralPath $Launcher.vbsPath) -and [IO.File]::ReadAllText($Launcher.vbsPath) -ceq $Launcher.content)
}

function Sync-KeeperOneShotTask {
    param([hashtable]$Config, [hashtable]$Plan, [string]$KeeperRoot, [string]$ConfigFile, [switch]$ReadOnlyRetry)
    $eventPrefix = if ($ReadOnlyRetry) { 'READ_RETRY' } else { 'ANCHOR_ALARM' }
    try {
        $existing = Get-ScheduledTask -TaskName $plan.taskName -ErrorAction SilentlyContinue
        if ($plan.action -eq 'clear') {
            if ($existing) {
                Unregister-ScheduledTask -TaskName $plan.taskName -Confirm:$false
                return @{ ok = $true; changed = $true; event = "${eventPrefix}_CLEARED"; taskName = $plan.taskName; targetAt = $null; reason = $plan.reason }
            }
            return @{ ok = $true; changed = $false; event = $null; taskName = $plan.taskName; targetAt = $null; reason = $plan.reason }
        }

        $launcher = Get-AnchorAlarmLauncherSpec -KeeperRoot $KeeperRoot -ConfigFile $ConfigFile -ReadOnlyRetry:$ReadOnlyRetry -ScheduleRecovery:([bool]$plan.scheduleRecovery) -NoWrite
        $action = New-ScheduledTaskAction -Execute $launcher.exe -Argument $launcher.arguments -WorkingDirectory (Get-KeeperRoot $KeeperRoot)
        $trigger = New-ScheduledTaskTrigger -Once -At $plan.targetAt
        $settingsParams = @{
            MultipleInstances = 'IgnoreNew'; ExecutionTimeLimit = (Get-KeeperTaskExecutionTimeLimit $Config).timeSpan
            StartWhenAvailable = $true; AllowStartIfOnBatteries = $true; DontStopIfGoingOnBatteries = $true
        }
        if ($Config.task.wakeToRun -eq $true) { $settingsParams.WakeToRun = $true }
        if ($Config.task.runIfNetworkAvailable -eq $true) { $settingsParams.RunOnlyIfNetworkAvailable = $true }
        $settings = New-ScheduledTaskSettingsSet @settingsParams
        $principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited
        if (Test-OneShotTaskMatches $existing $plan $launcher $action $settings $principal) {
            return @{ ok = $true; changed = $false; event = $null; taskName = $plan.taskName; targetAt = $plan.targetAt; reason = 'task already matches' }
        }
        $null = Get-AnchorAlarmLauncherSpec -KeeperRoot $KeeperRoot -ConfigFile $ConfigFile -ReadOnlyRetry:$ReadOnlyRetry -ScheduleRecovery:([bool]$plan.scheduleRecovery)
        Register-ScheduledTask -TaskName $plan.taskName -Action $action -Trigger $trigger -Settings $settings `
            -Principal $principal -Description "Codex Quota Keeper: $($plan.reason)." -Force | Out-Null
        return @{ ok = $true; changed = $true; event = "${eventPrefix}_SET"; taskName = $plan.taskName; targetAt = $plan.targetAt; reason = $plan.reason }
    } catch {
        return @{ ok = $false; changed = $false; event = $null; taskName = $plan.taskName; targetAt = $plan.targetAt; reason = (Hide-SensitiveText $_.Exception.Message) }
    }
}
